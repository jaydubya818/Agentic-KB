#!/usr/bin/env node
// Rebuilds navigation hubs under wiki/mocs/ for pages that are generated in
// bulk and would otherwise be orphans: nightly CI reports and bus escalations.
// Each hub is a dated, newest-first index — a real way to find "what did CI say
// last Tuesday" — not a link dump to move a metric.
//
//   node scripts/rebuild-orphan-hubs.mjs            # write hubs
//   node scripts/rebuild-orphan-hubs.mjs --check    # exit 1 if hubs are out of date
//
// Guarantees: idempotent (byte-stable when the file set is unchanged, so no
// daily churn), every emitted [[link]] is verified to resolve to a real file.
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const root = path.resolve(process.env.KB_REPO || path.join(path.dirname(fileURLToPath(import.meta.url)), '..'))
const wiki = path.join(root, 'wiki')
const check = process.argv.includes('--check')

const listMd = dir => {
  const abs = path.join(wiki, dir)
  return fs.existsSync(abs)
    ? fs.readdirSync(abs).filter(f => f.endsWith('.md') && f !== 'README.md').sort().reverse()
    : []
}
const stem = f => f.replace(/\.md$/, '')

const HUBS = [
  {
    file: 'nightly-ci-reports.md',
    title: 'Nightly CI Reports',
    intro: 'Every nightly CI analysis report, newest first. Use this to trace when a failure started or whether a fix held.',
    tags: ['ci', 'reports', 'hub'],
    dir: 'reports',
    filter: f => /nightly-ci-analysis/.test(f),
  },
  {
    file: 'bus-escalations.md',
    title: 'Bus Escalations',
    intro: 'Escalations published to the agentic-kb bus, newest first. Recurring "sandbox unavailable" aborts here point at infrastructure, not at code.',
    tags: ['bus', 'escalation', 'hub'],
    dir: 'repos/agentic-kb/bus/escalation',
    filter: () => true,
  },
]

function render(hub, links) {
  return `---
title: ${hub.title}
type: moc
category: structure
tags: [${hub.tags.join(', ')}]
created: 2026-10-11
updated: ${new Date().toISOString().slice(0, 10)}
---

# ${hub.title}

${hub.intro}

> Generated by \`scripts/rebuild-orphan-hubs.mjs\`. Regenerate; do not hand-edit.

${links.map(l => `- [[${l}]]`).join('\n')}
`
}
const strip = s => s.replace(/^updated: .*$/m, '')

let stale = 0
let bad = 0
for (const hub of HUBS) {
  const links = listMd(hub.dir).filter(hub.filter).map(f => `${hub.dir}/${stem(f)}`)
  // Verify every link resolves to a real file before writing anything.
  for (const l of links) {
    if (!fs.existsSync(path.join(wiki, `${l}.md`))) { console.error(`BROKEN: [[${l}]]`); bad++ }
  }
  const dest = path.join(wiki, 'mocs', hub.file)
  const prev = fs.existsSync(dest) ? fs.readFileSync(dest, 'utf8') : ''
  const next = render(hub, links)
  if (strip(prev) === strip(next)) { console.log(`current: mocs/${hub.file} (${links.length} links)`); continue }
  stale++
  if (check) { console.log(`out of date: mocs/${hub.file}`); continue }
  fs.mkdirSync(path.dirname(dest), { recursive: true })
  fs.writeFileSync(dest, next)
  console.log(`wrote: mocs/${hub.file} (${links.length} links)`)
}
if (bad) process.exit(2)
if (check && stale) process.exit(1)
