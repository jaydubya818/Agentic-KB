#!/usr/bin/env node
// Knowledge-quality checks beyond orphan/stale counts. Offline and fast.
//
//   node scripts/kb-quality.mjs --json            # machine-readable metrics on stdout
//   node scripts/kb-quality.mjs --write           # also write wiki/_meta/kb-quality.md
//
// Findings touching the active projects are ranked first: that is where a stale
// or contradictory page actually costs something.
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'
import { scanVault, coreMetrics, brokenLinks, evaluateFreshness } from './lib/kb-scan.mjs'

export const ACTIVE_PROJECTS = [
  { name: 'MyFactory', re: /my-?factory|software.factory/i },
  { name: 'MyEve', re: /my-?eve/i },
  { name: 'Relay', re: /\brelay\b/i },
  { name: 'MissionControl', re: /mission.?control/i },
  { name: 'FDLC', re: /\bfdlc\b/i },
]
const GENERIC_BASENAMES = /^(index|readme|home|hot|profile|gotchas|task-log|progress|claude|active-task|overview|log)$/i

export function analyze(root) {
  const { pages } = scanVault(root)
  const core = coreMetrics(pages)
  const byPath = new Map(pages.map(p => [p.relPath, p]))
  const proj = p => ACTIVE_PROJECTS.find(a => a.re.test(p.relPath) || a.re.test(p.title))?.name

  const broken = brokenLinks(pages, root)

  // Duplicate / overlapping knowledge: same normalized title or same slug in
  // different folders. Generic names (index, profile, …) legitimately repeat.
  const dup = new Map()
  for (const p of pages) {
    if (/^(_|archive|agents|repos|system\/bus|daily-systems)/.test(p.relPath)) continue
    const base = path.posix.basename(p.relPath, '.md')
    if (GENERIC_BASENAMES.test(base)) continue
    for (const key of new Set([`t:${String(p.title).toLowerCase().trim()}`, `s:${base.replace(/^(pattern|recipe|framework|concept|summary)-/, '')}`])) {
      if (!dup.has(key)) dup.set(key, [])
      dup.get(key).push(p.relPath)
    }
  }
  const duplicates = [...dup.entries()].map(([k, v]) => ({ key: k, pages: [...new Set(v)] })).filter(d => d.pages.length > 1)

  const decisions = pages.filter(p => /^decisions\//.test(p.relPath) && !/README/i.test(p.relPath))
  const unreferencedDecisions = decisions.filter(p => (core.inbound.get(p.relPath)?.length ?? 0) === 0).map(p => p.relPath)

  // Active-project coverage: pages that mention the project, whether a
  // home/overview exists, and whether project pages connect to concepts/patterns.
  const projects = ACTIVE_PROJECTS.map(a => {
    const mentioning = pages.filter(p => a.re.test(p.relPath) || a.re.test(p.title) || a.re.test(p.content || ''))
    const own = pages.filter(p => a.re.test(p.relPath) || a.re.test(p.title))
    const hasHome = own.some(p => /(^|\/)(home|index|overview|claude)\.md$/i.test(p.relPath) || /^repos\/[^/]+\/home\.md$/.test(p.relPath))
    const linksOut = own.flatMap(p => p.cleanLinks).filter(l => /(concepts|patterns|frameworks)\//.test(l) || /^(concepts|patterns)/.test(l))
    return { name: a.name, ownPages: own.length, mentions: mentioning.length, hasHome,
      conceptLinks: linksOut.length,
      gaps: [
        own.length === 0 && 'no dedicated wiki pages',
        own.length > 0 && !hasHome && 'no home/overview page',
        own.length > 0 && linksOut.length === 0 && 'no links to concepts/patterns/frameworks',
        mentioning.length > own.length * 3 + 5 && 'heavily mentioned elsewhere but thinly documented',
      ].filter(Boolean) }
  })

  // Agent instructions past 2x their cadence are likely obsolete.
  const obsoleteAgent = pages.filter(p => /^agents\//.test(p.relPath)).map(p => ({ p, f: evaluateFreshness(p) }))
    .filter(({ f }) => f.state === 'stale' && f.ageDays > f.days * 2).map(({ p, f }) => ({ page: p.relPath, ageDays: f.ageDays }))
  const outdatedPatterns = pages.filter(p => /^patterns\//.test(p.relPath)).filter(p => evaluateFreshness(p).state === 'stale').map(p => p.relPath)

  const priority = list => list.sort((a, b) => (proj(byPath.get(b.page || b)) ? 1 : 0) - (proj(byPath.get(a.page || a)) ? 1 : 0))
  return {
    pages: pages.length, orphans: core.orphans.length, stale: core.stale.length, stalePct: core.stalePct,
    verified: pages.filter(p => p.lastVerified).length,
    malformed: pages.filter(p => p.malformed).map(p => p.relPath),
    brokenLinks: priority(broken), duplicates, unreferencedDecisions,
    projects, obsoleteAgent, outdatedPatterns,
    orphanPaths: core.orphans.map(p => p.relPath), stalePaths: core.stale.map(p => p.relPath),
  }
}

export function renderReport(a) {
  const when = new Date().toISOString().slice(0, 10)
  const L = []
  L.push('---', 'title: KB Quality', 'type: moc', 'category: structure', 'tags: [maintenance, quality, generated]', `updated: ${when}`, '---', '',
    '# KB Quality', '', '> Generated by `scripts/kb-quality.mjs`. Complements [[_meta/kb-health]] with checks beyond orphan/stale counts.', '',
    '| Check | Count |', '|---|---|',
    `| Broken cross-references | ${a.brokenLinks.length} |`,
    `| Duplicate / overlapping topics | ${a.duplicates.length} |`,
    `| Decisions nothing references | ${a.unreferencedDecisions.length} |`,
    `| Agent instruction pages >2× past cadence | ${a.obsoleteAgent.length} |`,
    `| Patterns past review cadence | ${a.outdatedPatterns.length} |`,
    `| Pages with malformed front matter | ${a.malformed.length} |`,
    `| Pages with \`last_verified\` | ${a.verified} |`, '',
    '## Active projects', '', '| Project | Own pages | Mentions | Home page | Concept links | Gaps |', '|---|---|---|---|---|---|',
    ...a.projects.map(p => `| ${p.name} | ${p.ownPages} | ${p.mentions} | ${p.hasHome ? 'yes' : 'no'} | ${p.conceptLinks} | ${p.gaps.join('; ') || '—'} |`), '')
  const top = (title, rows, fmt) => rows.length && L.push(`## ${title}`, '', ...rows.slice(0, 15).map(fmt), rows.length > 15 ? `- …and ${rows.length - 15} more` : '', '')
  top('Broken cross-references (active projects first)', a.brokenLinks, r => `- \`${r.page}\` → \`${String(r.link).replace(/\|.*/, '')}\``)
  top('Possible duplicates', a.duplicates, d => `- ${d.pages.map(p => `\`${p}\``).join(' · ')}`)
  top('Unreferenced decisions', a.unreferencedDecisions, p => `- \`${p}\``)
  top('Agent instructions likely obsolete', a.obsoleteAgent, r => `- \`${r.page}\` (${r.ageDays}d old)`)
  top('Patterns awaiting verification', a.outdatedPatterns, p => `- \`${p}\``)
  top('Malformed front matter', a.malformed, p => `- \`${p}\``)
  return L.join('\n') + '\n'
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = path.resolve(process.env.KB_REPO || path.join(path.dirname(fileURLToPath(import.meta.url)), '..'))
  const a = analyze(root)
  if (process.argv.includes('--write')) {
    const dest = path.join(root, 'wiki/_meta/kb-quality.md')
    const next = renderReport(a)
    const strip = s => s.replace(/^updated: .*$/m, '')
    const prev = fs.existsSync(dest) ? fs.readFileSync(dest, 'utf8') : ''
    if (strip(prev) !== strip(next)) { fs.writeFileSync(dest, next); console.error('wrote wiki/_meta/kb-quality.md') }
  }
  if (process.argv.includes('--json')) {
    const { orphanPaths, stalePaths, ...summary } = a
    console.log(JSON.stringify({ ...summary, brokenLinks: a.brokenLinks.length, duplicates: a.duplicates.length,
      unreferencedDecisions: a.unreferencedDecisions.length, obsoleteAgent: a.obsoleteAgent.length,
      outdatedPatterns: a.outdatedPatterns.length, malformed: a.malformed.length,
      projectGaps: a.projects.reduce((n, p) => n + p.gaps.length, 0) }))
  }
}
